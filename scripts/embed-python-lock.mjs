import { mkdir, readFile, writeFile } from "node:fs/promises";

const source = "runtime/requirements.lock";
const destination = "src/modules/runtimeLock.ts";

const lock = await readFile(source, "utf8");
await mkdir("src/modules", { recursive: true });
await writeFile(
  destination,
  `// Generated by pnpm run python-lock:embed. Do not edit manually.\n// prettier-ignore\nexport const EMBEDDED_REQUIREMENTS_LOCK = ${JSON.stringify(lock)};\n`,
  "utf8",
);
